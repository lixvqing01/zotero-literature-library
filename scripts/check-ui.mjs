import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, channel: 'chromium' });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4179');
  await page.getByRole('button', { name: 'Attention Is All You Need', exact: true }).waitFor();
  // Gecko puts native XUL popup labels in the same chrome document as this HTML UI.
  // Exercise the actual stylesheet with both namespaces, even in the headless preview.
  const namespaceStyles = await page.evaluate(() => {
    const html = document.createElement('label');
    const native = document.createElementNS('http://www.mozilla.org/keymaster/gatekeeper/there.is.only.xul', 'label');
    native.classList.add('choice');
    html.textContent = native.textContent = 'Menu label fixture';
    document.body.append(html, native);
    const result = { html: getComputedStyle(html).display, native: getComputedStyle(native).display,
      nativeMargin: getComputedStyle(native).marginTop };
    html.remove(); native.remove(); return result;
  });
  assert.equal(namespaceStyles.html, 'flex');
  assert.notEqual(namespaceStyles.native, 'flex', 'Plugin CSS must not restyle native popup labels');
  assert.notEqual(namespaceStyles.nativeMargin, '13px');
  await page.screenshot({ path: 'test-output/ui-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Attention Is All You Need', exact: true }).click();
  await page.locator('#detail-dialog[open]').waitFor();
  await page.locator('[data-layer="outline"]').click();
  await page.locator('[data-section="s2"]').waitFor();
  await page.locator('[data-section="s2"]').click();
  await page.locator('#read-next:not([disabled])').waitFor();
  await page.locator('#read-next').click();
  await page.locator('#read-previous:not([disabled])').waitFor();
  await page.locator('#read-previous').click();
  await page.locator('#read-previous[disabled]').waitFor();
  await page.locator('#close-detail').click();
  await page.locator('#search-query').fill('Attention');
  await page.locator('#search-layer').selectOption('metadata');
  await page.locator('#search-mode').selectOption('hybrid');
  await page.locator('#search-form').evaluate(form => form.requestSubmit());
  await page.locator('#search-notice').filter({ hasText: '1 个结果' }).waitFor();
  await page.locator('#refresh').click();
  await page.locator('[data-tab="jobs"]').click();
  await page.locator('[data-retry="j2"]').click();
  await page.locator('#notification').filter({ hasText: '已重新排队；若再次失败会显示新的错误原因' }).waitFor();
  assert.equal(await page.locator('[data-retry="j2"]').count(), 0);
  assert.equal(await page.locator('[data-rebuild="d2"]').count(), 1);
  assert.equal(await page.locator('[data-retry="j4"]').textContent(), '恢复查询原任务');
  assert.equal(await page.locator('[data-rebuild="d4"]').count(), 1);
  await page.locator('[data-retry="j4"]').click();
  await page.locator('#notification').filter({ hasText: '已恢复查询原任务，不会重新上传 PDF' }).waitFor();
  const recovered = page.locator('tr').filter({ hasText: '面向科学文献的分层检索与证据定位' });
  await recovered.filter({ hasText: '等待上传确认' }).waitFor();
  assert.match(await recovered.textContent(), /不会重新上传 PDF/);
  assert.equal(await page.locator('[data-rebuild="d4"]').count(), 0);
  await page.locator('[data-tab="library"]').click();
  assert.equal(await page.locator('tr').filter({ hasText: '面向科学文献的分层检索与证据定位' }).count(), 0);
  assert.equal(await page.locator('#search-query').inputValue(), 'Attention');
  assert.equal(await page.locator('#search-layer').inputValue(), 'metadata');
  assert.equal(await page.locator('#search-mode').inputValue(), 'hybrid');
  assert.equal(await page.locator('#document-rows tr').count(), 1);
  await page.locator('#select-all').check();
  assert.equal(await page.locator('.row-check:checked').count(), 1);
  await page.locator('#clear-search').click();
  assert.equal(await page.locator('#document-rows tr').count(), 3);
  await page.locator('[data-tab="settings"]').click();
  assert.equal(await page.locator('#summary').isVisible(), false);
  await page.locator('#mineru-key').fill('fixture-not-a-real-secret');
  await page.locator('[data-settings-pane="embedding"]').click();
  await page.locator('[data-settings-pane="processing"]').click();
  assert.equal(await page.locator('#mineru-key').inputValue(), 'fixture-not-a-real-secret');
  await page.locator('#refresh').click();
  assert.equal(await page.locator('#mineru-key').inputValue(), 'fixture-not-a-real-secret');
  await page.getByRole('button', { name: '安全保存 Key', exact: true }).click();
  assert.equal(await page.locator('#mineru-key').inputValue(), '');
  await page.locator('#clear-key').click();
  await page.locator('#credential-state').filter({ hasText: '未配置' }).waitFor();
  await page.locator('[data-settings-pane="embedding"]').click();
  assert.equal(await page.locator('#model-source').inputValue(), 'modelscope');
  await page.locator('#test-embedding').click();
  await page.locator('#embedding-state').filter({ hasText: '测试通过' }).waitFor();
  await page.locator('input[name="embedding-provider"][value="api"]').check();
  await page.locator('#embedding-api-url').waitFor();
  assert.match(await page.locator('#embedding-state').innerText(), /保存 API Key/);
  await page.locator('#embedding-api-url').fill('https://embeddings.example.com/v1');
  await page.locator('#embedding-api-url').press('Tab');
  await page.locator('#embedding-api-key').fill('fixture-api-key-123456');
  await page.getByRole('button', { name: '安全保存 API Key' }).click();
  await page.locator('.setup-footer').filter({ hasText: '向量 API Key 已保存' }).waitFor();
  await page.locator('#test-embedding').click();
  await page.locator('#embedding-state').filter({ hasText: '测试通过' }).waitFor();
  await page.screenshot({ path: 'test-output/ui-embedding-api.png', fullPage: true });
  await page.locator('#clear-embedding-key').click();
  await page.locator('.section-title .badge').filter({ hasText: '未配置 API Key' }).waitFor();
  assert.equal((await page.locator('#embedding-state').innerText()).includes('测试通过'), false);
  await page.locator('[data-settings-pane="agents"]').click();
  await page.locator('#install-codex').click();
  await page.locator('#notification').filter({ hasText: 'Codex MCP 配置已写入' }).waitFor();
  await page.locator('#install-claude').click();
  await page.locator('#notification').filter({ hasText: 'Claude Code MCP 配置已写入' }).waitFor();
  await page.screenshot({ path: 'test-output/ui-agents.png', fullPage: true });
  await page.locator('#copy-config').click();
  const copied = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(copied.mcpServers.zotero_literature_library.headers.Authorization, 'Bearer preview-token');
  assert.equal(copied.mcpServers.zotero_literature_library.type, 'http');
  await page.locator('[data-settings-pane="processing"]').click();
  await page.screenshot({ path: 'test-output/ui-settings.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-output/ui-mobile-settings.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.locator('[data-tab="library"]').click();
  await page.screenshot({ path: 'test-output/ui-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('UI desktop/mobile, reading pagination, persisted search, local/API embedding setup, agent configuration and credential forms passed.');
} finally { await browser.close(); }
